async function uploadPlaceholders(client, tag, count = 4) {
  const folders = await client.listAssets({ include_folders: true, query: JSON.stringify({ is_dir: true }) }).catch(() => []);
  const folder = folders.find((f) => f.is_dir && f.name === 'Lorem Ipsum' && !f.parent_uid) || await client.createFolder('Lorem Ipsum');
  const out = [];
  for (let i = 0; i < count; i++) {
    const [a, b] = PALETTES[(Date.now() + i) % PALETTES.length];
    const blob = new Blob([gradientPng(1200, 800, a, b)], { type: 'image/png' });
    out.push(await client.uploadAsset(blob, {
      filename: `lorem-ipsum-${suffix()}.png`, title: `Lorem ipsum placeholder ${i + 1}`,
      description: 'Placeholder image generated by Stack Toolkit', parentUid: folder.uid, tags: [tag],
    }));
  }
  return out;
}

// --- schema ------------------------------------------------------------------------

// Content types referenced anywhere in a schema (reference fields, JSON RTE embeds), through global fields and blocks.
function referencedCts(schema, gfs, seen = new Set()) {
  const out = new Set();
  const walk = (fields) => {
    for (const f of fields || []) {
      if (f.data_type === 'reference') [].concat(f.reference_to || []).forEach((c) => out.add(c));
      if (f.data_type === 'global_field' && !seen.has(f.reference_to)) {
        seen.add(f.reference_to);
        walk(gfs.get(f.reference_to)?.schema);
      }
      walk(f.schema);
      for (const b of f.blocks || []) {
        if (b.reference_to && !seen.has(b.reference_to)) { seen.add(b.reference_to); walk(gfs.get(b.reference_to)?.schema); }
        walk(b.schema);
      }
    }
  };
  walk(schema);
  return out;
}

const isImage = (a) => /^image\//.test(a.content_type || '') && !/svg/.test(a.content_type);
const extOf = (name) => (String(name).match(/\.([a-z0-9]+)$/i)?.[1] || '').toLowerCase();

// --- the generator -----------------------------------------------------------------

function createGenerator({ gfs, refPool, assets, images, tag }) {
  const warnings = new Map(); // path → message
  const warn = (path, msg) => { if (!warnings.has(path)) warnings.set(path, `${path}: ${msg}`); };

  function times(f, make) {
    if (!f.multiple) return make();
    const max = Math.min(Number(f.max_instance) || 3, 3);
    return Array.from({ length: int(1, Math.max(1, max)) }, make);
  }

  // Builds a string for simple patterns: literals, \\d \\w, [a-z0-9-] classes and {n} {n,m} ? + * quantifiers.
  function fromPattern(re) {
    const src = re.replace(/^\^/, '').replace(/\$$/, '');
    const ALNUM = 'abcdefghijklmnopqrstuvwxyz0123456789';
    let out = '';
    for (let i = 0; i < src.length;) {
      let chars;
      if (src[i] === '\\') {
        const c = src[i + 1];
        chars = c === 'd' ? '0123456789' : c === 'w' ? ALNUM : c === 's' ? ' ' : c;
        i += 2;
      } else if (src[i] === '[') {
        const end = src.indexOf(']', i);
        if (end < 0 || src[i + 1] === '^') return null;
        chars = '';
        const body = src.slice(i + 1, end).replace(/\\d/g, '0-9').replace(/\\w/g, 'a-zA-Z0-9_');
        for (let j = 0; j < body.length; j++) {
          if (body[j + 1] === '-' && body[j + 2]) {
            for (let c = body.charCodeAt(j); c <= body.charCodeAt(j + 2); c++) chars += String.fromCharCode(c);
            j += 2;
          } else chars += body[j] === '\\' ? body[++j] : body[j];
        }
        i = end + 1;
      } else if ('()|.'.includes(src[i])) return null;
      else chars = src[i++];
      let [min, max] = [1, 1];
      const q = src.slice(i).match(/^(\{(\d+)(?:,(\d*))?\}|[?+*])/);
      if (q) {
        if (q[1] === '?') [min, max] = [0, 1];
        else if (q[1] === '+') [min, max] = [1, 6];
        else if (q[1] === '*') [min, max] = [0, 6];
        else [min, max] = [Number(q[2]), q[3] === undefined ? Number(q[2]) : q[3] === '' ? Number(q[2]) + 5 : Number(q[3])];
        i += q[1].length;
      }
      for (let n = int(min, max); n > 0; n--) out += pick([...chars]);
    }
    return out;
  }

  function matchesFormat(f, v) {
    if (!f.format) return true;
    try { return new RegExp(f.format).test(v); } catch { return true; }
  }

  function text(f, path) {
    const meta = f.field_metadata || {};
    let v;
    // Plain single-line fields are also recognized by name: slugs, URLs, e-mails, phones.
    const plain = !meta.allow_rich_text && !meta.markdown && !meta.multiline;
    const name = f.uid.toLowerCase();
    if (f.uid === 'title') v = cap(words(2, 5));
    else if (f.uid === 'url') v = `/lorem-ipsum/${slug(words(2, 3))}`;
    else if (plain && /slug/.test(name)) v = slug(words(2, 4));
    else if (plain && /(^|_)(url|link|href|website)($|_)/.test(name)) v = `https://www.example.com/${slug(words(2, 3))}`;
    else if (plain && /e_?mail/.test(name)) v = `lorem.${suffix()}@example.com`;
    else if (plain && /phone|mobile|tel($|_)/.test(name)) v = `+48 ${int(500, 899)} ${int(100, 999)} ${int(100, 999)}`;
    else if (meta.allow_rich_text) {
      const img = images.length && Math.random() < 0.5 ? `<p><img src="${pick(images).url}" alt="Lorem ipsum"></p>` : '';
      v = `<h2>${cap(words(2, 5))}</h2><p>${paragraph()}</p>${img}<ul>${Array.from({ length: 3 }, () => `<li>${cap(words(2, 6))}</li>`).join('')}</ul><p>${paragraph()}</p>`;
    } else if (meta.markdown) {
      v = `## ${cap(words(2, 5))}\n\n${paragraph()}\n\n- ${cap(words(2, 6))}\n- ${cap(words(2, 6))}\n\n${paragraph()}`;
    } else if (meta.multiline) v = paragraph();
    else v = cap(words(2, 6));

    if (f.unique) v = /^[/a-z0-9-]+$/.test(v) ? `${v}-${suffix()}` : `${v} ${suffix()}`;
    if (f.format && !matchesFormat(f, v)) {
      const id = suffix();
      const candidates = [`lorem.${id}@example.com`, `https://www.example.com/lorem-${id}`, `lorem-ipsum-${id}`,
        `/lorem-ipsum/${id}`, String(int(100000, 999999)), `LOREM${id.toUpperCase()}`, `Lorem ${id}`];
      v = candidates.find((c) => matchesFormat(f, c));
      for (let i = 0; !v && i < 5; i++) {
        const g = fromPattern(f.format);
        if (g !== null && matchesFormat(f, g)) v = g;
      }
      if (!v) { warn(path, `doesn't match its validation pattern ${f.format} – left empty`); return undefined; }
    }
    if (Number(f.max) > 0 && v.length > f.max) v = v.slice(0, f.max);
    return v;
  }

  function choice(f) {
    const vals = (f.enum?.choices || []).map((c) => c.value).filter((v) => v !== undefined && v !== '');
    if (!vals.length) return undefined;
    return f.multiple ? sample(vals, int(1, Math.min(2, vals.length))) : pick(vals);
  }

  function number(f) {
    const min = Number.isFinite(f.min) ? f.min : 1;
    const max = Number.isFinite(f.max) ? f.max : Math.max(min, 1000);
    return int(Math.ceil(min), Math.floor(Math.max(min, max)));
  }

  function date(f) {
    const d = new Date(Date.now() - int(0, 365) * 86400_000 + int(0, 86400) * 1000);
    return f.field_metadata?.hide_time ? d.toISOString().slice(0, 10) : d.toISOString();
  }

  function file(f, path) {
    const meta = f.field_metadata || {};
    const exts = [].concat(f.extensions || meta.extensions || []).map((e) => String(e).toLowerCase().replace(/^\./, ''));
    let pool = meta.image ? images : assets;
    if (exts.length) pool = assets.filter((a) => exts.includes(extOf(a.filename)));
    if (!pool.length) {
      warn(path, f.mandatory ? 'required, but there is no suitable asset – entries may be rejected' : 'no suitable asset – left empty');
      return undefined;
    }
    return f.multiple ? sample(pool, int(1, Math.min(3, pool.length))).map((a) => a.uid) : pick(pool).uid;
  }

  function reference(f, path) {
    const cts = [].concat(f.reference_to || []);
    const options = cts.flatMap((ct) => (refPool.get(ct) || []).map((uid) => ({ uid, _content_type_uid: ct })));
    if (!options.length) {
      warn(path, `${f.mandatory ? 'required, but ' : ''}no entries of ${cts.join(', ')} to reference – left empty`);
      return undefined;
    }
    const multiple = f.field_metadata?.ref_multiple ?? f.multiple;
    return multiple ? sample(options, int(1, Math.min(3, options.length))) : [pick(options)];
  }

  function jsonRte(f) {
    const node = (type, children, attrs = {}) => ({ type, uid: rteUid(), attrs, children });
    const children = [
      node('h2', [{ text: cap(words(2, 5)) }]),
      node('p', [{ text: `${sentence()} ` }, { text: cap(words(2, 4)), bold: true }, { text: ` ${paragraph()}` }]),
      node('ul', Array.from({ length: 3 }, () => node('li', [{ text: cap(words(2, 6)) }]))),
      node('p', [{ text: paragraph() }]),
    ];
    if (images.length && [].concat(f.reference_to || []).includes('sys_assets') && Math.random() < 0.6) {
      const a = pick(images);
      children.splice(2, 0, node('reference', [{ text: '' }], {
        'display-type': 'display', type: 'asset', 'asset-uid': a.uid, 'content-type-uid': 'sys_assets',
        'asset-link': a.url, 'asset-name': a.filename, 'asset-type': a.content_type, 'class-name': 'embedded-asset',
      }));
    }
    return { type: 'doc', uid: rteUid(), attrs: {}, children };
  }

  function value(f, path) {
    if (f.extension_uid) { warn(path, 'custom field (extension) – skipped'); return undefined; }
    switch (f.data_type) {
      case 'text': return f.enum ? choice(f) : times(f, () => text(f, path));
      case 'number': return f.enum ? choice(f) : times(f, () => number(f));
      case 'boolean': return Math.random() < 0.5;
      case 'isodate': return times(f, () => date(f));
      case 'file': return file(f, path);
      case 'reference': return reference(f, path);
      case 'link': return times(f, () => ({ title: cap(words(1, 3)), href: `https://www.example.com/${slug(words(1, 3))}` }));
      case 'group': return times(f, () => fields(f.schema, path));
      case 'global_field': {
        const gf = gfs.get(f.reference_to);
        if (!gf) { warn(path, `global field ${f.reference_to} not found – skipped`); return undefined; }
        return times(f, () => fields(gf.schema, path));
      }
      case 'blocks': {
        const blocks = (f.blocks || []).map((b) => ({ uid: b.uid, schema: b.reference_to ? gfs.get(b.reference_to)?.schema : b.schema }));
        if (!blocks.length) return undefined;
        const max = Math.min(Number(f.max_instance) || 4, 4);
        return Array.from({ length: int(1, max) }, () => {
          const b = pick(blocks);
          return { [b.uid]: fields(b.schema || [], `${path} › ${b.uid}`) };
        });
      }
      case 'json':
        if (f.field_metadata?.allow_json_rte) return times(f, () => jsonRte(f));
        warn(path, 'JSON field – skipped');
        return undefined;
      case 'taxonomy': warn(path, 'taxonomy – skipped'); return undefined;
      default: warn(path, `unsupported field type "${f.data_type}" – skipped`); return undefined;
    }
  }

  // fill: 'all' fields or only 'required' ones (plus the title).
  let fillMode = 'all';
  function fields(schema, parent = '') {
    const out = {};
    for (const f of schema || []) {
      if (fillMode === 'required' && !f.mandatory && f.uid !== 'title') continue;
      const path = parent ? `${parent} › ${f.uid}` : f.uid;
      const v = value(f, path);
      if (v !== undefined) out[f.uid] = v;
    }
    return out;
  }

  return {
    warnings,
    entry(schema, { fill = 'all', locale, master } = {}) {
      fillMode = fill;
      const e = fields(schema);
      // Localized versions: master-only fields are left out and the title shows the language.
      if (locale && locale !== master) {
        for (const f of schema) if (f.non_localizable) delete e[f.uid];
        if (typeof e.title === 'string') e.title = `[${locale}] ${e.title}`;
      }
      e.tags = [tag];
      return e;
    },
  };
}

// --- preparation, preview and run --------------------------------------------------

const OPTS_DEFAULTS = { count: 10, locales: [], assetMode: 'existing', fill: 'all', tag: 'lorem-ipsum' };

async function prepare(client, ct, opts, onProgress) {
  onProgress({ step: 'Reading the schema, locales and assets…' });
  const [cts, gfList, locales, assetList] = await Promise.all([
    client.listContentTypes(), client.listGlobalFields().catch(() => []), listLocalesBrief(client),
    opts.assetMode === 'existing' ? client.listAssets() : Promise.resolve([]),
  ]);
  const ctDef = cts.find((c) => c.uid === ct);
  if (!ctDef) throw new Error(`Content type ${ct} not found.`);
  const gfs = new Map(gfList.map((g) => [g.uid, g]));
  const master = locales.find((l) => l.master)?.code || locales[0]?.code;
  const known = new Set(locales.map((l) => l.code));
  const extra = (opts.locales || []).filter((l) => l !== master && known.has(l));

  // Existing entries to reference – the first 200 of each referenced content type.
  const refPool = new Map();
  for (const ref of referencedCts(ctDef.schema, gfs)) {
    if (!cts.some((c) => c.uid === ref)) continue;
    onProgress({ step: `Reading entries to reference: ${ref}` });
    const list = await client.listEntries(ref, { locale: master, 'only[BASE][]': ['title', 'locale'] }).catch(() => []);
    refPool.set(ref, list.filter((e) => e.locale === master).slice(0, 200).map((e) => e.uid));
  }

  const files = assetList.filter((a) => !a.is_dir);
  return { ctDef, gfs, master, extra, refPool, assets: files, images: files.filter(isImage) };
}

export function normalizeLoremOptions(o = {}) {
  const opts = { ...OPTS_DEFAULTS, ...o };
  opts.count = Math.trunc(Number(opts.count));
  if (!(opts.count >= 1 && opts.count <= 500)) throw new Error('Number of entries must be between 1 and 500.');
  if (!['existing', 'placeholder', 'none'].includes(opts.assetMode)) throw new Error('Invalid asset option.');
  if (!['all', 'required'].includes(opts.fill)) throw new Error('Invalid fill option.');
  if (!Array.isArray(opts.locales) || !opts.locales.every((l) => /^[a-z]{2,3}(-[a-z0-9]+)*$/i.test(l))) throw new Error('Invalid locales.');
  opts.tag = String(opts.tag || '').trim().toLowerCase();
  if (!/^[a-z0-9][a-z0-9_-]{0,49}$/.test(opts.tag)) throw new Error('The tag may contain letters, digits, - and _ (max 50).');
  return opts;
}

// A sample entry without writing anything (placeholder images are shown as such).
export async function previewLorem(client, ct, opts, { onProgress = () => {} } = {}) {
  const p = await prepare(client, ct, opts, onProgress);
  const fake = { uid: '(placeholder image)', url: 'placeholder.png', filename: 'lorem-ipsum.png', content_type: 'image/png' };
  const gen = createGenerator({
    gfs: p.gfs, refPool: p.refPool, tag: opts.tag,
    assets: opts.assetMode === 'placeholder' ? [fake] : p.assets,
    images: opts.assetMode === 'placeholder' ? [fake] : p.images,
  });
  const sample = gen.entry(p.ctDef.schema, { fill: opts.fill, master: p.master });
  return {
    contentType: { uid: ct, title: p.ctDef.title },
    master: p.master,
    locales: [p.master, ...p.extra],
    sample,
    warnings: [...gen.warnings.values()],
    assets: { mode: opts.assetMode, available: p.assets.length, images: p.images.length },
  };
}

export async function generateLorem(client, ct, opts, { onProgress = () => {}, concurrency = 4 } = {}) {
  const p = await prepare(client, ct, opts, (x) => onProgress({ ...x }));
  let { assets, images } = p;
  if (opts.assetMode === 'placeholder') {
    onProgress({ step: 'Uploading placeholder images…' });
    images = await uploadPlaceholders(client, opts.tag);
    assets = images;
  }
  const gen = createGenerator({ gfs: p.gfs, refPool: p.refPool, assets, images, tag: opts.tag });
  const total = opts.count;
  let done = 0;
  const created = [];
  const failed = [];
  await pool(Array.from({ length: total }, (_, i) => i + 1), concurrency, async () => {
    try {
      const entry = await client.createEntry(ct, gen.entry(p.ctDef.schema, { fill: opts.fill, master: p.master }), { locale: p.master });
      created.push(entry.uid);
      for (const locale of p.extra) {
        await client.updateEntry(ct, entry.uid, gen.entry(p.ctDef.schema, { fill: opts.fill, locale, master: p.master }), { locale });
      }
      onProgress({ ok: true, uid: entry.uid, title: entry.title });
    } catch (e) {
      failed.push(e.message);
      onProgress({ ok: false, error: e.message });
    }
    done++;
    onProgress({ step: `Creating entries: ${done} / ${total}`, done, total });
  });
  return { created, failed, placeholders: opts.assetMode === 'placeholder' ? images.length : 0, warnings: [...gen.warnings.values()] };
}
