// Lorem Ipsum: fills a content type with generated test entries, following its schema.
//
// Every field type is generated from the schema – text (incl. multiline, Markdown, HTML and JSON RTE), numbers,
// booleans, dates, selects, links, groups, global fields and modular blocks, recursively. References point at
// existing entries, file fields at existing assets or at placeholder PNGs uploaded once per run.
// Custom fields (extensions) and taxonomies are skipped and reported.
// Every generated entry and placeholder asset gets a tag (default "lorem-ipsum"), so they're easy to find and delete.
import { deflateSync } from 'node:zlib';
import { randomBytes } from 'node:crypto';
import { listLocalesBrief, pool } from './entries.js';

const WORDS = ('lorem ipsum dolor sit amet consectetur adipiscing elit sed do eiusmod tempor incididunt ut labore et dolore '
  + 'magna aliqua ut enim ad minim veniam quis nostrud exercitation ullamco laboris nisi ut aliquip ex ea commodo consequat '
  + 'duis aute irure dolor in reprehenderit in voluptate velit esse cillum dolore eu fugiat nulla pariatur excepteur sint '
  + 'occaecat cupidatat non proident sunt in culpa qui officia deserunt mollit anim id est laborum').split(' ');

const int = (min, max) => min + Math.floor(Math.random() * (max - min + 1));
const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];
const sample = (arr, n) => [...arr].sort(() => Math.random() - 0.5).slice(0, n);
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const words = (min, max) => Array.from({ length: int(min, max) }, () => pick(WORDS)).join(' ');
const sentence = () => `${cap(words(6, 14))}.`;
const paragraph = () => Array.from({ length: int(2, 4) }, sentence).join(' ');
const suffix = () => randomBytes(3).toString('hex');
const rteUid = () => randomBytes(16).toString('hex');
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

